#!/usr/bin/env node
/**
 * Generates the reference pages of this site from the Kanade repository.
 *
 *   node scripts/sync-content.mjs            # reads ../kanade
 *   KANADE_SRC=/path/to/kanade node scripts/sync-content.mjs
 *
 * Only pages whose value is verbatim precision are generated:
 *
 *   reference/config-defaults      the TOML defaults block from Configuration.md
 *   reference/cli                  the full verb table from CLI.md
 *   reference/domain-language      CONTEXT.md
 *   reference/known-gaps/*         Limitations.md, split by area, bullets verbatim
 *   decisions/index                the ADR table, each title linking into the repository
 *
 * Everything else under src/content/docs is hand-written. Guides, per-area
 * configuration pages and the short CLI pages are authored here on purpose:
 * they summarize and cross-link instead of mirroring the wiki. Edits to the
 * generated pages belong in the Kanade repository; run this again to pick them
 * up. Hand-written pages are never touched or pruned.
 *
 * Conversions applied to generated pages:
 *  - the first H1 becomes `title` in the frontmatter and is removed from the body;
 *  - links into the repository point at the matching page of this site, and
 *    anything without a counterpart here becomes a github.com blob URL;
 *  - GitHub alert blockquotes become `:::note`/`:::tip`/`:::caution`/`:::danger` asides.
 * Prose is otherwise copied verbatim.
 */
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE_ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const KANADE = path.resolve(process.env.KANADE_SRC ?? path.join(SITE_ROOT, '..', 'kanade'));
const CONTENT = path.join(SITE_ROOT, 'src', 'content', 'docs');
const REPO_BLOB = 'https://github.com/0x1d1e/kanade/blob/main/';
const ADR_DIR = 'docs/adr';

if (!existsSync(path.join(KANADE, ADR_DIR))) {
  console.error(`Kanade source not found at ${KANADE}. Set KANADE_SRC to the repository root.`);
  process.exit(1);
}

/** The marker every generated file carries. `check:length` skips files that have it. */
const GENERATED_MARKER = '<!-- Generated by scripts/sync-content.mjs';

/**
 * Repository source -> the page on this site that covers it. A source with no
 * entry is linked as a blob URL in the repository.
 */
const SITE_PATHS = new Map([
  ['docs/wiki/Home.md', '/'],
  ['docs/wiki/Installation.md', '/getting-started/installation/'],
  ['docs/wiki/Keyboard.md', '/getting-started/keybinds/'],
  ['docs/wiki/CLI.md', '/cli/'],
  ['docs/wiki/Configuration.md', '/configuration/'],
  ['docs/wiki/Settings.md', '/configuration/'],
  ['docs/wiki/Agent-hooks.md', '/integrations/agent-hooks/'],
  ['docs/wiki/Dictation.md', '/integrations/dictation/'],
  ['docs/wiki/Google-Calendar.md', '/integrations/google-calendar/'],
  ['docs/wiki/SDDM.md', '/integrations/sddm/'],
  ['docs/wiki/Limitations.md', '/reference/known-gaps/'],
  ['CONTEXT.md', '/reference/domain-language/'],
  ['docs/branding.md', '/reference/branding/'],
]);

/** Resolves one link target written in `sourceFile` to a site path or a GitHub URL. */
function resolveTarget(target, sourceFile) {
  if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith('#') || target.startsWith('//')) {
    return target;
  }
  const hashAt = target.indexOf('#');
  const hash = hashAt === -1 ? '' : target.slice(hashAt);
  const pathname = hashAt === -1 ? target : target.slice(0, hashAt);
  const absolute = path.resolve(path.dirname(sourceFile), decodeURI(pathname));
  const relative = path.relative(KANADE, absolute).split(path.sep).join('/');

  const site = SITE_PATHS.get(relative);
  if (site) return site + hash;
  return REPO_BLOB + relative + hash;
}

/** Rewrites markdown links, leaving code fences and inline code alone. */
function rewriteLinks(markdown, sourceFile) {
  const lines = markdown.split('\n');
  let fence = false;
  return lines
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) {
        fence = !fence;
        return line;
      }
      if (fence) return line;
      return line
        .split(/(`[^`]*`)/g)
        .map((chunk) =>
          chunk.startsWith('`') && chunk.endsWith('`') && chunk.length > 1
            ? chunk
            : chunk.replace(/(!?\[[^\]]*\]\()([^)\s]+)(\))/g, (_all, open, target, close) => {
                return open + resolveTarget(target, sourceFile) + close;
              })
        )
        .join('');
    })
    .join('\n');
}

const ALERT_TYPES = {
  NOTE: 'note',
  TIP: 'tip',
  IMPORTANT: 'note',
  WARNING: 'caution',
  CAUTION: 'danger',
};

/** Converts GitHub `> [!TYPE]` blockquotes into Starlight `:::type` asides. */
function convertAlerts(markdown) {
  const lines = markdown.split('\n');
  const out = [];
  let fence = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*(```|~~~)/.test(line)) {
      fence = !fence;
      out.push(line);
      continue;
    }
    const alert = !fence && /^> \[!([A-Z]+)\]\s*$/.exec(line);
    if (!alert || !ALERT_TYPES[alert[1]]) {
      out.push(line);
      continue;
    }
    const body = [];
    i++;
    while (i < lines.length && /^>/.test(lines[i])) {
      body.push(lines[i].replace(/^> ?/, ''));
      i++;
    }
    i--;
    while (body.length && body[0].trim() === '') body.shift();
    while (body.length && body[body.length - 1].trim() === '') body.pop();
    out.push(`:::${ALERT_TYPES[alert[1]]}`, ...body, ':::');
  }
  return out.join('\n');
}

/** Splits a source file into its H1 title and the remaining body. */
function splitTitle(markdown, sourceFile) {
  const lines = markdown.split('\n');
  let fence = false;
  let headingAt = -1;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*(```|~~~)/.test(line)) {
      fence = !fence;
      continue;
    }
    if (fence) continue;
    if (/^#\s+/.test(line)) {
      headingAt = i;
      break;
    }
  }
  if (headingAt === -1) throw new Error(`No H1 in ${sourceFile}`);
  const title = lines[headingAt].replace(/^#\s+/, '').trim();
  const body = lines.slice(headingAt + 1).join('\n').replace(/^\n+/, '');
  return { title, body };
}

function frontmatter(fields) {
  const entries = Object.entries(fields).filter(([, value]) => value !== undefined);
  return ['---', ...entries.map(([key, value]) => `${key}: ${JSON.stringify(value)}`), '---'].join('\n');
}

function generatedNote(source) {
  // The file name only: the built HTML keeps this comment, and a repository path in it would
  // read as a leftover link. The README says where the sources live.
  return `${GENERATED_MARKER} from ${path.basename(source)}. Edit the source in the Kanade repository, then run npm run sync. -->`;
}

async function writePage(slug, fields, body, source) {
  const file = path.join(CONTENT, `${slug}.md`);
  await mkdir(path.dirname(file), { recursive: true });
  const content = [frontmatter(fields), '', generatedNote(source), '', body.trim(), ''].join('\n');
  await writeFile(file, content);
  return file;
}

