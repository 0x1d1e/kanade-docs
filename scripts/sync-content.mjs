// --- prune -----------------------------------------------------------------

// Only generated pages are pruned: a stale reference page goes away, a
// hand-written page is never a candidate.
const keep = new Set(written.map((file) => path.relative(CONTENT, file)));
async function prune(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await prune(full);
      if ((await readdir(full)).length === 0) await rm(full, { recursive: true });
      continue;
    }
    const relative = path.relative(CONTENT, full);
    if (keep.has(relative)) continue;
    const content = await readFile(full, 'utf8');
    if (content.includes(GENERATED_MARKER)) await rm(full);
  }
}
